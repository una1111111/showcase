/* 卡片内的叙事小模块（如「🎯 项目背景与数据洞察」），
   paragraphs = 普通段落；points = 带加粗引导词的要点 */
export interface ProjectSection {
  icon: string // 模块 emoji
  title: string // 模块标题
  paragraphs?: string[]
  points?: { lead: string; text: string }[]
}

